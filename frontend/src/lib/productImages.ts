export function getProductImageUrl(product: {
  slug?: string;
  name?: string;
  category?: string;
  imageUrl?: string;
}): string {
  // If product has an image URL from unsplash, use it
  if (product.imageUrl && product.imageUrl.includes("images.unsplash.com")) {
    return product.imageUrl;
  }

  // Exact slug match
  if (product.slug && PRODUCT_IMAGE_MAP[product.slug]) {
    return PRODUCT_IMAGE_MAP[product.slug];
  }

  // Keyword match on name
  if (product.name) {
    const lowerName = product.name.toLowerCase();
    for (const [slug, url] of Object.entries(PRODUCT_IMAGE_MAP)) {
      const slugTerms = slug.split("-");
      if (slugTerms.some((t) => t.length > 3 && lowerName.includes(t))) {
        return url;
      }
    }
  }

  // Category fallback
  if (product.category && CATEGORY_FALLBACK_IMAGES[product.category]) {
    return CATEGORY_FALLBACK_IMAGES[product.category];
  }

  return CATEGORY_FALLBACK_IMAGES.default;
}
